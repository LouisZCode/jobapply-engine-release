# ATS process plumbing: security/verification codes the apply flow itself generates.
# Part of the application paper trail (the user: "these are part of the process"), so
# they are FILED under the label + archived — but they are never outcome evidence, so NO
# event is written. Checked BEFORE the noise filter (which would otherwise leave them
# sitting in the inbox untouched).
PROCESS_CODE = re.compile(
    r"security code|sicherheitscode|verification code|verifizierungscode|"
    r"one-?time (code|passcode|pin)|einmal(code|kennwort|passwort)|best[aä]tigungscode", re.I)

# account-plumbing subjects: password/account-setup mail the apply flow itself
# generates (2026-07-17 extension — previously silently absorbed by NOISE, where it
# sat in the inbox untouched forever). Concrete phrases only (never a bare
# "passwort"/"password" token) so a bank/personal account mail can't slip in.
ACCOUNT_PLUMBING = re.compile(
    r"passwort erstellen|create (your )?password|set (up )?(your )?password|"
    r"karriere.?account erstellt|account (created|erstellt)|applicant profile|"
    r"sign in and continue your application|continue your application", re.I)
# broadens the anchor beyond JOBSUBJ to a bare "karriere"/"applicant" subject token
# (Capgemini "Karriere Account erstellt" / Dynatrace "applicant profile" carry no
# bewerbung/application wording for JOBSUBJ to catch) — still requires a
# PROCESS_CODE/ACCOUNT_PLUMBING phrase too, so this alone can never anchor a mail.
CAREER_SUBJ = re.compile(r"karriere|applicant", re.I)


def is_process_mail(r):
    """True for ATS process plumbing anchored to the application process: an ATS
    sender (ATS_DOM), an application-shaped subject (JOBSUBJ), or a bare
    career/applicant-portal subject token (CAREER_SUBJ). Two subject shapes qualify
    once anchored: PROCESS_CODE (security/verification codes) or ACCOUNT_PLUMBING
    (password/account-setup mail). linkedin.com is excluded outright, unconditionally
    — LinkedIn security/password mail is sacred and must never be filed here, even if
    its subject happens to be anchor+plumbing-shaped."""
    if "linkedin.com" in (r["from_domain"] or "").lower():
        return False
    subj = nfc(r["subject"])
    anchored = bool(ATS_DOM.search(r["from_domain"]) or JOBSUBJ.search(subj) or CAREER_SUBJ.search(subj))
    return anchored and bool(PROCESS_CODE.search(subj) or ACCOUNT_PLUMBING.search(subj))


def files_as_process(r):
    """OUTCOME MAIL ALWAYS WINS: a mail files as plumbing ONLY when it classifies to
    nothing else. is_process_mail() looks at the subject alone, so a real assessment /
    rejection / ack whose subject happens to be plumbing-shaped ("Continue your
    application: next steps...", "Update to your ... applicant profile") would
    otherwise be archived event-less — silent data loss. classify() is the veto."""
    return is_process_mail(r) and classify(r) == "other"


# ============================================================================
# Rollup  (ported verbatim: terminal latest-wins, else highest rung)
# ============================================================================
TERM = {"rejection": "rejected", "offer": "offer", "withdrawn": "withdrawn"}
RUNG = {"interview_scheduled": "interviewing", "interview_done": "interviewing",
        "invite": "invited", "assessment_request": "assessment", "auto_ack": "acknowledged"}
ORD = ["interviewing", "invited", "assessment", "acknowledged"]


def recompute(cur, job):
    evs = cur.execute("SELECT event_at,event_type FROM application_events WHERE job_id=?", (job,)).fetchall()
    term = [(a, t) for a, t in evs if t in TERM]
    if term:
        a, t = max(term)
        oc, ocat = TERM[t], a
    else:
        best = None
        bat = None
        for a, t in evs:
            rr = RUNG.get(t)
            if rr and (best is None or ORD.index(rr) < ORD.index(best)):
                best, bat = rr, a
            elif rr and rr == best and a > bat:
                bat = a
        oc, ocat = (best, bat) if best else ("no_response", None)
    cur.execute("UPDATE applications SET outcome=?,outcome_at=? WHERE job_id=?", (oc, ocat, job))
    return oc


def has_stage_event(cur, job_id):
    """True if job_id already has a real hiring-stage event (invite / interview /
    assessment) on file. Used to corroborate an 'offer' classification: an offer
    mail with NO prior stage event is unusual enough that the user wants to confirm
    it manually before it's filed as a real offer (2026-07-17 hardening)."""
    row = cur.execute(
        "SELECT 1 FROM application_events WHERE job_id=? AND event_type IN "
        "('invite','interview_scheduled','interview_done','assessment_request') LIMIT 1",
        (job_id,)).fetchone()
    return row is not None


