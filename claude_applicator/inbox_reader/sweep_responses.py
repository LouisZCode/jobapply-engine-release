def _http_status(exc):
    """Best-effort int HTTP status out of a googleapiclient HttpError."""
    try:
        return int(exc.resp.status)
    except Exception:
        return None


def _retry(fn, what):
    """Call fn(); retry transient Gmail/network failures up to 3 total attempts
    (sleeps 2s then 8s between them). Anything else, or the 3rd failure, is
    re-raised unchanged (2026-07-11: an unbounded Gmail read hung the sweep for
    ~3h; socket.setdefaulttimeout(120) below bounds any single read, and this
    retries the transient cases instead of dying outright)."""
    delays = (2, 8)
    for attempt in range(3):
        try:
            return fn()
        except (TimeoutError, socket.timeout, OSError) as e:
            if attempt == 2:
                raise
            print("WARN: {} failed ({}); retry {}/3 in {}s".format(
                what, e, attempt + 2, delays[attempt]), file=sys.stderr)
            time.sleep(delays[attempt])
        except HttpError as e:
            status = _http_status(e)
            if status not in (429, 500, 502, 503, 504) or attempt == 2:
                raise
            print("WARN: {} failed (HTTP {}); retry {}/3 in {}s".format(
                what, status, attempt + 2, delays[attempt]), file=sys.stderr)
            time.sleep(delays[attempt])


class _TextExtract(HTMLParser):
    def __init__(self):
        super().__init__()
        self.chunks = []
        self._skip = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self._skip += 1

    def handle_endtag(self, tag):
        if tag in ("script", "style") and self._skip:
            self._skip -= 1

    def handle_data(self, data):
        if not self._skip:
            self.chunks.append(data)


def _html_to_text(html):
    ex = _TextExtract()
    try:
        ex.feed(html)
    except Exception:
        pass
    return " ".join(" ".join(ex.chunks).split())


def _decode_parts(payload):
    """Yield decoded text of every text/plain and text/html part (recursive)."""
    stack = [payload]
    while stack:
        p = stack.pop()
        mt = p.get("mimeType", "")
        data = (p.get("body") or {}).get("data")
        if data and mt in ("text/html", "text/plain"):
            try:
                txt = base64.urlsafe_b64decode(data.encode()).decode("utf-8", "replace")
                yield (mt, txt)
            except Exception:
                pass
        for sub in p.get("parts") or []:
            stack.append(sub)


def _hdr(v):
    """Decode an RFC2047-encoded header (=?UTF-8?..?= -> Müller)."""
    if not v:
        return ""
    try:
        return str(make_header(decode_header(v)))
    except Exception:
        return v


def _body_text(payload):
    plain, html = "", ""
    for mt, txt in _decode_parts(payload):
        if mt == "text/plain" and not plain:
            plain = txt
        elif mt == "text/html" and not html:
            html = txt
    # Some ATSes (Sopra Steria) send text/plain that still carries HTML entities
    # (f&uuml;r, &nbsp;) — unescape so the German patterns see "für"; the HTML path
    # is already entity-decoded by HTMLParser. \xa0 is what &nbsp; becomes.
    txt = unescape(plain.strip()) if plain.strip() else _html_to_text(html)
    return re.sub(r"[ \t\xa0]+", " ", txt).strip()[:4000]


def _event_at(full, hdr):
    """Original send time preferred (Date header -> UTC); fall back to Gmail's
    internalDate (epoch ms, always UTC). Both -> 'YYYY-MM-DD HH:MM:SS' UTC."""
    try:
        dt = parsedate_to_datetime(hdr.get("date"))
        if dt is not None:
            return dt.astimezone(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    except Exception:
        pass
    ms = full.get("internalDate")
    if ms:
        return datetime.datetime.fromtimestamp(int(ms) / 1000, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    return ""


def build_r(full):
    payload = full.get("payload", {})
    hdr = {h["name"].lower(): h["value"] for h in payload.get("headers", [])}
    frm = _hdr(hdr.get("from"))
    m = re.search(r"@([A-Za-z0-9.\-]+)", frm)
    dom = m.group(1).lower().rstrip(">") if m else ""
    return {
        "gid": full["id"],                                   # Gmail id (for modify)
        "from": frm,
        "from_domain": dom,
        "subject": _hdr(hdr.get("subject")),
        "date_utc": _event_at(full, hdr),
        "message_id": (hdr.get("message-id") or "").strip(),  # RFC822 -> DB msg_id
        "body": _body_text(payload),
    }


def get_or_create_label(svc, name):
    labels = _retry(lambda: svc.users().labels().list(userId="me").execute(),
                     "labels.list").get("labels", [])
    for lab in labels:
        if lab["name"] == name:
            return lab["id"]
    created = svc.users().labels().create(
        userId="me",
        body={"name": name, "labelListVisibility": "labelShow", "messageListVisibility": "show"},
    ).execute()
    return created["id"]


def list_inbox(svc, q, cap):
    ids, tok = [], None
    while len(ids) < cap:
        resp = _retry(lambda: svc.users().messages().list(
            userId="me", q=q, maxResults=min(100, cap - len(ids)), pageToken=tok).execute(),
            "messages.list")
        ids += [m["id"] for m in (resp.get("messages") or [])]
        tok = resp.get("nextPageToken")
        if not tok:
            break
    return ids


