def _watchdog(signum, frame):
    print("WATCHDOG: sweep exceeded 15min — aborting", file=sys.stderr)
    sys.exit(2)


def main():
    # Whole-run watchdog (Part 2 hardening, 2026-07-11 hang class): if the sweep
    # is still running after 15 minutes for ANY reason, abort loudly rather than
    # hang for hours. Covers the dry-run path too (armed unconditionally here).
    signal.signal(signal.SIGALRM, _watchdog)
    signal.alarm(900)

    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true",
                    help="full match+classify + report, but write/move NOTHING")
    ap.add_argument("--auth", action="store_true",
                    help="one-time interactive consent for gmail.modify, then exit")
    ap.add_argument("--since-days", type=int, default=14)
    ap.add_argument("--max", type=int, default=300, help="safety cap on messages examined")
    ap.add_argument("--debug", action="store_true")
    a = ap.parse_args()

    if a.auth:
        get_service(scopes=SCOPES_MODIFY, token_file=TOKEN_MODIFY, allow_consent=True)
        print("OK — gmail.modify consent stored in", os.path.basename(TOKEN_MODIFY))
        signal.alarm(0)
        return

    ts = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    lines = []

    def emit(msg=""):
        print(msg)
        lines.append(msg)

    # Bound any single Gmail HTTP read so a hung connection can't block for
    # hours (2026-07-11: a read hung ~3h before the process died rc=1).
    socket.setdefaulttimeout(120)

    # --- auth (never opens a browser in the scheduled path) ---
    try:
        svc = get_service(scopes=SCOPES_MODIFY, token_file=TOKEN_MODIFY)
    except Exception as e:
        print("ERROR: gmail.modify token unavailable ({}). Run: "
              "sweep_responses.py --auth".format(e), file=sys.stderr)
        signal.alarm(0)
        sys.exit(2)

    # --- match corpus from the DB (applied rows, incl. manual-* pre-agent rows) ---
    con = sqlite3.connect(DB)
    cur = con.cursor()
    cur.execute("PRAGMA foreign_keys=ON")
    # star-once ledger (schema.sql carries the same DDL) — self-creates so a
    # pre-migration DB just works on its first LIVE run. Not in --dry-run, which
    # must write NOTHING (not even idempotent DDL); the ledger read below falls
    # back to empty when the table doesn't exist yet.
    if not a.dry_run:
        cur.execute(
            "CREATE TABLE IF NOT EXISTS starred_msgs (msg_id TEXT PRIMARY KEY, starred_at TEXT NOT NULL)")
    applied = cur.execute(
        "SELECT job_id,company,title,substr(applied_at,1,10) FROM applications WHERE status='applied'").fetchall()
    corpus = build_corpus(applied)
    done = set(x[0] for x in cur.execute(
        "SELECT msg_id FROM application_events WHERE msg_id IS NOT NULL"))
    try:
        starred_msgs = set(x[0] for x in cur.execute("SELECT msg_id FROM starred_msgs"))
    except sqlite3.OperationalError:   # dry-run against a pre-migration DB: no table yet
        starred_msgs = set()

    mode = "DRY-RUN" if a.dry_run else "LIVE"
    emit("==== mail sweep {}   [{}]  (F-4 Part E / LOOP-002) ====".format(ts, mode))
    emit("DB: {}   applied rows: {}   companies: {}".format(
        os.path.abspath(DB), len(applied), len(corpus)))

    q = "in:inbox newer_than:{}d".format(a.since_days)
    ids = list_inbox(svc, q, a.max)
    emit("query: '{}'  ->  {} message(s) in inbox window\n".format(q, len(ids)))

    label_id = None if a.dry_run else get_or_create_label(svc, LABEL_NAME)

    recorded, flags, noise_rows, own, already, unrelated_rows = [], [], [], 0, 0, []
    process_rows = []
    for gid in ids:
        full = _retry(lambda: svc.users().messages().get(userId="me", id=gid, format="full").execute(),
                      "messages.get")
        r = build_r(full)
        frm_l = nfc(r["from"]).lower()

        if any(addr in frm_l for addr in _USER_MAIL["self_emails"]):
            own += 1
            continue
        # ATS process plumbing (application security/verification codes): file under
        # the label + archive, NO event. Must run BEFORE the noise filter, which also
        # matches code subjects but would leave them sitting in the inbox.
        if files_as_process(r):
            process_rows.append(r)
            if not a.dry_run:
                _move(svc, gid, label_id, archived=True)
            continue
        if (NOISE.search(nfc(r["subject"])) or NOISE_DOM.search(r["from_domain"])
                or NOISE_FROM.search(nfc(r["from"]))):
            noise_rows.append(r)
            continue

        et = classify(r)
        job, comp, conf = resolve(r, corpus)
        matched = job is not None and conf == "high"

        if matched and et == "offer" and not has_stage_event(cur, job):
            # Offer with no invite/interview/assessment history on file: unusual
            # enough (wrong match? scam? backlog gap?) that the user wants to confirm
            # it by hand rather than auto-file it as a real offer.
            flags.append((r, et, comp, "offer-without-interview-history — confirm manually"))
            if not a.dry_run:                       # pre-file: label + ledger-star ("offer"
                _move(svc, gid, label_id, archived=False)   # is a KEEP_TYPE), keep in inbox,
                _apply_star(svc, gid, et, r["message_id"], starred_msgs, cur, con)  # no event
            continue

        if not (matched and et in ACTIONABLE):
            # Not confidently actionable. Flag ONLY if it looks like a job response;
            # otherwise it's just other inbox mail -> leave it, don't clutter the report.
            if et in ACTIONABLE:                       # real response type, weak/no match
                reason = "no confident company match" if job is None else "low-confidence match"
                if et in KEEP_TYPES:
                    # KEEP_TYPE-shaped mail the user must not miss even without a confident
                    # company match (2026-07-17 Part B — closes the "second Sopra invite
                    # got NOTHING" hole): label it into the sweep view + ledger-star it.
                    # Still no DB event — unsure -> never write.
                    reason += " (labeled+starred — REAL invite-shaped mail, triage!)"
                    if not a.dry_run:
                        _move(svc, gid, label_id, archived=False)
                        _apply_star(svc, gid, et, r["message_id"], starred_msgs, cur, con)
                flags.append((r, et, comp, reason))
            elif matched:                              # matched company but unclassifiable body
                flags.append((r, et, comp, "matched but couldn't classify (other)"))
                if not a.dry_run:                      # pre-file: label only, keep in inbox,
                    _move(svc, gid, label_id, archived=False)  # no star, no event — a manual
                # archive by the user then lands it in the sweep label instead of bare All Mail
            elif ATS_DOM.search(r["from_domain"]) or JOBSUBJ.search(nfc(r["subject"])):
                flags.append((r, et, comp, "job-looking (ATS/subject) but unmatched + unclassified"))
            else:
                unrelated_rows.append(r)                # not job mail -> leave silently
            continue

        archived = et in ARCHIVE_TYPES
        if r["message_id"] in done:
            # event already written on a prior run; only the label-move (or the star,
            # per the ledger) may have failed or predated the feature — both heal here.
            already += 1
            if not a.dry_run:
                _move(svc, gid, label_id, archived)
                _apply_star(svc, gid, et, r["message_id"], starred_msgs, cur, con)
            recorded.append((r, et, job, comp, archived, "re-filed"))
            continue

        if not a.dry_run:
            cur.execute(
                "INSERT OR IGNORE INTO application_events "
                "(job_id,event_at,event_type,source,msg_id,sender,subject,notes,created_at) "
                "VALUES (?,?,?,?,?,?,?,?,datetime('now'))",
                (job, r["date_utc"], et, "gmail-agent", r["message_id"],
                 r["from"][:120], r["subject"][:200], "nightly gmail sweep"))
            con.commit()                    # event committed BEFORE the mail is moved
            new_outcome = recompute(cur, job)
            con.commit()
            done.add(r["message_id"])
            _move(svc, gid, label_id, archived)
            _apply_star(svc, gid, et, r["message_id"], starred_msgs, cur, con)
        else:
            new_outcome = "(dry)"
        recorded.append((r, et, job, comp, archived, new_outcome))

    # ---- report ----
    arch_n = sum(1 for x in recorded if x[4])
    kept_n = len(recorded) - arch_n
    emit("-- RECORDED ({}) : event written{} --".format(
        len(recorded), "" if a.dry_run else "  |  archived {} / kept-in-inbox {} (stars ledger-managed)".format(arch_n, kept_n)))
    for r, et, job, comp, archived, oc in sorted(recorded, key=lambda x: x[0]["date_utc"]):
        emit("  {} {:20} {:22} {:34} -> {} [{}]{}".format(
            r["date_utc"][:10], et, (comp or "?")[:22], nfc(r["subject"])[:34], job,
            "archived" if archived else "kept", "" if a.dry_run else "  outcome=" + str(oc)))

    if process_rows:
        emit("\n-- PROCESS ({}) : ATS codes/verifications — labeled + archived, NO event --".format(
            len(process_rows)))
        for rr in sorted(process_rows, key=lambda x: x["date_utc"]):
            emit("  {} {:24} {}".format(rr["date_utc"][:10], rr["from_domain"][:24], nfc(rr["subject"])[:50]))

    emit("\n-- FLAGS ({}) : left in inbox, triage (matched ones get the label; rest untouched) --".format(len(flags)))
    for r, et, comp, reason in sorted(flags, key=lambda x: x[0]["date_utc"]):
        emit("  {} {:20} {:22} {:34} ?? {}".format(
            r["date_utc"][:10], et, (comp or "?")[:22], nfc(r["subject"])[:34], reason))

    if a.debug:
        emit("\n-- DEBUG unrelated ({}) : 'other' + no company match, left silently --".format(len(unrelated_rows)))
        for rr in sorted(unrelated_rows, key=lambda x: x["date_utc"]):
            emit("  {} {:24} {}".format(rr["date_utc"][:10], rr["from_domain"][:24], nfc(rr["subject"])[:50]))
        emit("-- DEBUG noise ({}) : hit a non-outcome filter --".format(len(noise_rows)))
        for rr in sorted(noise_rows, key=lambda x: x["date_utc"]):
            emit("  {} {:24} {}".format(rr["date_utc"][:10], rr["from_domain"][:24], nfc(rr["subject"])[:50]))

    emit("\nexamined {} | recorded {} | process-filed {} | flagged {} | noise {} | unrelated {} | own {} | already-done {}".format(
        len(ids), len(recorded), len(process_rows), len(flags), len(noise_rows), len(unrelated_rows), own, already))
    emit("mode: {}{}".format(mode, "  (nothing written or moved)" if a.dry_run else ""))
    con.close()

    # ---- write the log mirror ----
    try:
        os.makedirs(OUTDIR, exist_ok=True)
        logpath = os.path.join(OUTDIR, "mail_sweep_{}.log".format(ts))
        with open(logpath, "w") as f:
            f.write("\n".join(lines) + "\n")
        print("\n(log written to {})".format(logpath))
    except Exception as e:
        print("WARN: could not write log: {}".format(e), file=sys.stderr)

    signal.alarm(0)


def _move(svc, gid, label_id, archived):
    """Add the sweep label; drop INBOX only for archive-type events. Best-effort: a
    failure leaves the mail in the inbox to be re-filed next run (event already
    saved). Starring is a separate concern now (see should_star/_star/_apply_star)
    — the star-once ledger, not this call, decides whether a mail gets STARRED."""
    body = {"addLabelIds": [label_id]}
    if archived:
        body["removeLabelIds"] = ["INBOX"]
    try:
        _retry(lambda: svc.users().messages().modify(userId="me", id=gid, body=body).execute(),
               "messages.modify")
    except Exception as e:
        print("WARN: label-move failed for {}: {}".format(gid, e), file=sys.stderr)


def _star(svc, gid):
    """Add STARRED to a message via gmail.modify (through _retry). Returns True on
    success, False on a swallowed failure — same warn-to-stderr style as _move. A
    False here leaves msg_id out of starred_msgs, so the next run retries the star."""
    try:
        _retry(lambda: svc.users().messages().modify(
            userId="me", id=gid, body={"addLabelIds": ["STARRED"]}).execute(),
            "messages.modify(star)")
        return True
    except Exception as e:
        print("WARN: star failed for {}: {}".format(gid, e), file=sys.stderr)
        return False


def should_star(et, msg_id, starred_set):
    """True iff this mail should get a STARRED add right now: its classification is
    a KEEP_TYPE (invite/assessment/interview/offer — mail the user must act on) AND its
    RFC822 msg_id has never been recorded in the star-once ledger. Ledger-gated so a
    star that failed, or predates this feature, self-heals on the next run — while a
    manual unstar by the user (once msg_id is in the ledger) sticks forever."""
    return et in KEEP_TYPES and msg_id not in starred_set


def _apply_star(svc, gid, et, msg_id, starred_set, cur, con):
    """Ledger-gated star: calls _star() only when should_star() says so, and on
    success records msg_id in starred_msgs (in-memory set + committed DB row) so it
    is never re-starred. No-op, no ledger write, on a swallowed _star() failure —
    the next run retries (msg_id still absent from the ledger)."""
    if should_star(et, msg_id, starred_set):
        if _star(svc, gid):
            starred_set.add(msg_id)
            cur.execute(
                "INSERT OR IGNORE INTO starred_msgs (msg_id, starred_at) VALUES (?, datetime('now'))",
                (msg_id,))
            con.commit()


