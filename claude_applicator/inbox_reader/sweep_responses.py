def ckey(s):
    s = nfc(s).lower()
    s = re.sub(r"\(.*?\)", " ", s)
    s = re.sub(r"\b(gmbh|ag|inc|ltd|co|kg|se|ug|holding|group|gruppe|"
               r"haftungsbeschr[aä]nkt|technologies|company|the)\b", " ", s)
    return re.sub(r"[^a-z0-9]+", "", s)


ALIASES_PATH = os.path.join(HERE, "company_aliases.txt")


def load_aliases(path=ALIASES_PATH):
    """Parse company_aliases.txt into {ckey(alias): canonical_company_name}. Format:
    'Alias => Canonical Name', one per line; blank lines and '#' comments ignored. A
    missing file yields {} (never fatal — this is a match booster, not required
    plumbing). Keyed by ckey() so lookups line up with company_candidates()'s own
    normalization. The module-level ALIASES below can be monkeypatched directly by
    tests (assign to sweep_responses.ALIASES) without touching the file."""
    aliases = {}
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or "=>" not in line:
                    continue
                alias, canon = line.split("=>", 1)
                alias, canon = alias.strip(), canon.strip()
                if alias and canon:
                    aliases[ckey(alias)] = canon
    except OSError:
        pass
    return aliases


ALIASES = load_aliases()   # alias ckey -> canonical company name (see company_aliases.txt)


def _d(s):
    try:
        y, m, dd = map(int, s[:10].split("-"))
        return datetime.date(y, m, dd)
    except Exception:
        return None


def _brand(domain):
    """Registrable brand token: cosuno.de -> cosuno, pwc.co.uk -> pwc; '' if <3 chars."""
    labels = (domain or "").split(".")
    if len(labels) < 2:
        return ""
    b = labels[-2]
    if b in _GENERIC_SLD and len(labels) >= 3:
        b = labels[-3]
    return b if len(b) >= 3 else ""


_SUBJ_PATTERNS = [
    r"applying to (?:join )?(.+?)(?:\s*[!|]|,|\.|$| stay tuned)",
    r"application (?:at|to) (.+?)(?:\s*[!|]|,|\.|$)",
    r"Bewerbung bei\s+([^,|!.]+?)(?:\s*(?:f[üu]r|als)\b|[!|]|,|\.|$)",
    r"interest in\s+(.+?)(?:\s*[!|]|,|\.|$)",
    # "Bewerbung als <Role> ... bei <Company>" (HeyJobs et al. put the company LAST)
    r"Bewerbung als .{0,80}?\bbei\s+([^,|!.]+?)\s*$",
    # "<Role> @ <Company>" (Ashby/join.com convention; company is the trailing token)
    r"@ ([A-Za-z0-9][^,|!.@]{1,40}?)\s*$",
]
_TEAM_CLEAN = (r"\b(hiring team|talent( acquisition)? team|recruiting team|recruitment|careers?|recruiting|"
               r"team|via softgarden|hr|no-?reply|notifications?)\b")


def company_candidates(r):
    """Sender-anchored company guesses, best-first: subject phrase, then display
    name, then the sender-domain brand. NEVER body tokens (they mis-match badly)."""
    cands = []
    subj = nfc(r["subject"])
    for pat in _SUBJ_PATTERNS:
        m = re.search(pat, subj, re.I)
        if m and len(m.group(1).strip()) > 2:
            cands.append(re.split(r"\s+(?:f[üu]r|als|for)\s+", m.group(1).strip())[0])
    disp = nfc(r["from"]).split("<")[0].strip().strip('"')
    disp = re.sub(_TEAM_CLEAN, "", disp, flags=re.I).strip(" -|·,")
    if disp:
        cands.append(disp)
    brand = _brand(r["from_domain"])
    if brand:
        cands.append(brand)
    # compound names ("ZIRKEL8 – TIECORP UG") also try each SPACED-dash segment —
    # spaced dashes only, so hyphenated brands like "U-Glow" stay intact
    for c in list(cands):
        if re.search(r"\s[–—-]\s", c):
            cands.extend(seg.strip() for seg in re.split(r"\s[–—-]\s", c) if len(seg.strip()) > 2)
    return [c for c in cands if c]


# distinctive-token stoplist for multi-row (same company, several roles) tie-breaks
_TITLE_STOP = {"engineer", "developer", "application", "solution", "solutions",
               "senior", "full", "stack", "fullstack", "agentic", "platform"}


def build_corpus(applied):
    """ckey -> [(job_id, company, title, applied_YYYY-MM-DD)]. A company is indexed under
    its normalized name AND any parenthetical brand, so "Prelytics (U-Glow GmbH)" is found
    by a response naming either 'Prelytics' or 'U-Glow' (the parenthetical match-miss)."""
    corpus = {}
    for job, co, ti, ap_at in applied:
        row = (job, co, ti, ap_at)
        keys = {ckey(co)}
        for paren in re.findall(r"\((.*?)\)", co or ""):
            k = ckey(paren)
            if len(k) >= 3:
                keys.add(k)
        for k in keys:
            if k:
                corpus.setdefault(k, []).append(row)
    return corpus


def resolve(r, corpus):
    """Return (job_id, label, confidence). confidence 'high' = safe to act.

    corpus: dict ckey(company) -> [(job_id, company, title, applied_YYYY-MM-DD)].
    Only an EXACT ckey hit is trusted (single row, or multi-row disambiguated by
    date+title with a clear margin). Substring/tie/undated/predating -> 'low'
    (flagged, never written) to honour "unsure -> don't touch". A candidate that
    misses the corpus directly is also tried through ALIASES (company_aliases.txt):
    an alias hit resolves to its canonical company's candidate, so mail sent under
    a different brand than the one applied to (e.g. a VC/portfolio mailer) still
    matches exactly like seeing the canonical name."""
    ed = _d(r["date_utc"])
    hit = None
    for cand in company_candidates(r):
        ck = ckey(cand)
        hit = corpus.get(ck)
        if not hit:
            canon = ALIASES.get(ck)
            if canon:
                hit = corpus.get(ckey(canon))
        if hit:
            break
    if not hit:
        return (None, None, "low")               # no confident company -> flag
    if len(hit) == 1:
        return (hit[0][0], hit[0][1], "high")

    # multi-row company: score by title-token overlap (x200) + date proximity
    hay = nfc(r["subject"] + " " + r["body"][:500]).lower()
    scored = []
    for job, co, ti, ap in hit:
        tt = [w for w in re.split(r"[^a-z0-9]+", nfc(ti).lower())
              if len(w) >= 4 and w not in _TITLE_STOP]
        tsc = sum(1 for w in tt if w in hay)
        ap_d = _d(ap)
        dd = (ed - ap_d).days if (ed and ap_d) else -999
        dscore = 60 if dd == 0 else (30 - dd if 1 <= dd <= 45 else (8 if dd == -1 else -900))
        scored.append((tsc * 200 + dscore, job, co, dd))
    scored.sort(reverse=True)
    if scored[0][0] < -800:                      # mail predates every application
        return (None, hit[0][1], "low")
    if len(scored) == 1 or scored[0][0] - scored[1][0] >= 10:
        return (scored[0][1], scored[0][2], "high")
    return (None, hit[0][1], "low")              # tie -> flag


