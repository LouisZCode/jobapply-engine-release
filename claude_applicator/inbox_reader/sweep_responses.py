def _load_user_mail():
    """Load inbox_reader/user_mail.json (generated by setup/render_templates.py from
    claude_applicator/profile.yaml). No fallback to any hard-coded personal values —
    this is the ONLY source for the sweep label and the self-mail addresses used to
    filter the user's own outgoing mail out of the sweep. Loaded at import time
    because other modules (mail_agent_tool.py) import LABEL_NAME from here."""
    path = os.path.join(HERE, "user_mail.json")
    if not os.path.isfile(path):
        sys.exit(
            "ERROR: {} not found.\n"
            "Run setup/render_templates.py first (it derives this file from "
            "claude_applicator/profile.yaml) — see PRODUCT_INVENTORY.md.".format(path)
        )
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except Exception as e:
        sys.exit("ERROR: could not parse {}: {}".format(path, e))
    emails = [e.strip().lower() for e in (data.get("self_emails") or []) if e and e.strip()]
    label = (data.get("label") or "").strip()
    if not emails or not label:
        sys.exit(
            "ERROR: {} is missing 'self_emails' or 'label'. Re-run "
            "setup/render_templates.py.".format(path)
        )
    return {"self_emails": emails, "label": label}


