#!/usr/bin/env python3
"""F-4 Part E / LOOP-002 — nightly Gmail sweep: response mail -> application_events.

Deterministic, no LLM (same philosophy as the F-2 reader). Reads the Gmail inbox,
matches each mail to an applied job, classifies the response, writes an
`application_events` row, recomputes that job's `outcome` rollup, and files the
mail under the user's configured sweep label (inbox_reader/user_mail.json, see
`_load_user_mail()` below) so the Main inbox stays clean.

THE INBOX IS THE WORK QUEUE. Query `in:inbox newer_than:<N>d`; archive-type mail
(acks/rejections) leaves the inbox (label added, INBOX removed) so the next run
never sees it again. Keep-type mail (invites/interviews/offers) stays in the inbox
and is STARRED on first record so the user notices it; the star is added once — if
the user unstars it, later re-file passes won't re-star. `msg_id UNIQUE` + INSERT OR
IGNORE makes a crash mid-loop or a re-run a pure no-op.

GUARDRAILS (identical spirit to F-2, stricter on writes):
  * READ + LABEL only. Never send, never delete, never reply, never touch a mail
    that did not produce a committed event. gmail.modify CAN trash mail; we never do.
  * UNSURE -> DON'T TOUCH. A mail is acted on ONLY when the company match is
    high-confidence AND it classifies to a recognized response type. Everything
    else stays in the inbox and is listed in the report's FLAGS section for the user.
  * NEVER touches pipeline fields (status / applied_at / extra_questions). It only
    INSERTs events and recomputes outcome/outcome_at. Worst case == today: the
    outcome stays whatever it was until better evidence arrives.
  * A mail leaves the inbox only AFTER its event row is committed — with ONE carve-out
    (the user, 2026-07-13): ATS process plumbing (application security/verification
    codes, is_process_mail) is labeled + archived with NO event; it is paper trail,
    never outcome evidence. Matched-but-unclassifiable flags get the LABEL only (stay
    in the inbox, no star, no event) so a later manual archive files them properly.

Match/classify logic is ported from the validated 2026-07-09 backlog import
(import_reference/pass2_commit.py) — sender-ANCHORED company matching (domain /
display-name / subject, NEVER body tokens) + the subject-anchored classifier with
the ack-subject guard (a clear receipt subject = auto_ack even when the body
carries "leider"/"unfortunately"/GDPR boilerplate — the #1 false-rejection trap).

Usage:
  sweep_responses.py --dry-run          # full match+classify, print, write/move NOTHING
  sweep_responses.py                     # live: write events + move mail
  sweep_responses.py --auth              # one-time interactive consent (gmail.modify)
  sweep_responses.py [--since-days 14] [--max 300] [--debug]
"""
