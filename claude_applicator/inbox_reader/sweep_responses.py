def classify(r):
    """One event type per mail. Order matters: definitive rejection first, then the
    ack-subject guard (clear receipt subject beats body boilerplate), then the rest."""
    s = nfc(r["subject"]).lower()
    full = s + " " + nfc(r["body"]).lower()
    if re.search(REJECT_STRONG, full):
        return "rejection"
    if re.search(r"testgorilla|hackerrank|codility|online[- ]?(test|assessment)|coding (challenge|test)|"
                 r"complete (a|the|this|your) (short )?(test|assessment|challenge)|case study", full):
        return "assessment_request"
    if re.search(ACK_SUBJ, s) and not re.search(UPDATE_SUBJ, s):
        return "auto_ack"                       # clear receipt subject -> ack, ignore body boilerplate
    if re.search(UPDATE_SUBJ, s) and re.search(SOFTNEG, full):
        return "rejection"
    if re.search(LEIDER, full):
        return "rejection"
    if re.search(r"job offer|offer of employment|offer letter|pleased to offer you|"
                 r"we would like to offer you|vertragsangebot|arbeitsvertrag|einstellungszusage", full):
        return "offer"
    if re.search(r"invitation|invite you|you.?re invited|einladung|\binterview\b|schedule (a )?(call|screening|chat|interview)|"
                 r"screening call|let.?s (meet|talk|chat)|you.?ve progressed|kennenlern|zum gespr[aä]ch|"
                 r"would like to (meet|speak|talk|invite|schedule)", s):
        return "invite"
    # invite hiding behind a neutral subject: BODY booking-ACTION phrases only ("book a
    # slot in my calendar", calendly). Deliberately narrow — pleasantries like
    # "freuen uns, dich kennenzulernen" appear in plain acks and must NOT fire here.
    if re.search(r"(slot|termin) in meinem kalender|kalender .{0,15}buchen|einen termin (zu )?buchen|"
                 r"calendly\.com|book (a|your) (slot|time|meeting|call)", full):
        return "invite"
    if re.search(r"received|eingang|erhalten|thanks for applying|wir haben deine bewerbung|application submitted|"
                 r"we.?ve received|danke für deine bewerbung|eingangsbest[aä]tigung|dein interesse an|"
                 r"freuen uns.{0,20}bewerbung|"
                 # receipt phrasings that only live in the BODY (safe here: every rejection
                 # check above has already declined the mail before this fallback runs)
                 r"thank(s| you)( so much)? for (submitting|your interest)|"
                 r"review(ing)? your application|"
                 r"bedanken uns f[üu]r (deine|ihre) bewerbung", full):
        return "auto_ack"
    return "other"


