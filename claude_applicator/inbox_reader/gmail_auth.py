#!/usr/bin/env python3
"""Shared Gmail auth for the inbox tools (F-2 reader + F-4 nightly sweep).

One place for the OAuth dance so every inbox tool shares the same OAuth *client*
(credentials.json) while keeping SEPARATE, scope-specific cached tokens:

  * F-2 verification reader   -> gmail.readonly, token.json          (read-only, injection-safe)
  * F-4 nightly sweep (LOOP-002) -> gmail.modify, token_modify.json
        (needs to remove the INBOX label after a response is recorded — nothing more)

The tokens are kept apart on purpose: the read-only reader can NEVER gain write
power by sharing a token, and re-authing one never disturbs the other. gmail.modify
grants read + label/trash + SEND (Google's own label: "read, compose, and send"),
yet it is the MINIMAL scope that can file a message — even adding a label goes through
messages.modify and there is no label-only scope. The sweep only ever adds a label
and removes INBOX; "never send, never delete" is enforced behaviourally, and by
keeping this token separate from the read-only reader's.
"""
import os
import sys

from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials
from google_auth_oauthlib.flow import InstalledAppFlow
from googleapiclient.discovery import build

# Scope constants — reference these by name at call sites, never inline the URL.
SCOPES_READONLY = ["https://www.googleapis.com/auth/gmail.readonly"]
SCOPES_MODIFY = ["https://www.googleapis.com/auth/gmail.modify"]

HERE = os.path.dirname(os.path.abspath(__file__))
CREDS = os.path.join(HERE, "credentials.json")
TOKEN_READONLY = os.path.join(HERE, "token.json")        # F-2 (unchanged)
TOKEN_MODIFY = os.path.join(HERE, "token_modify.json")   # F-4 sweep (LOOP-002)

# Back-compat aliases (older code referenced the bare-default names).
SCOPES = SCOPES_READONLY
TOKEN = TOKEN_READONLY


def get_service(*, scopes=SCOPES_READONLY, token_file=TOKEN_READONLY,
                allow_consent: bool = False):
    """Return an authenticated Gmail service for the given scopes + token cache.

    Defaults reproduce F-2 EXACTLY (read-only, token.json), so existing callers
    that do `get_service()` are byte-for-byte unchanged. The sweep passes
    `scopes=SCOPES_MODIFY, token_file=TOKEN_MODIFY`.

    allow_consent=False (default — for unattended runs): NEVER opens a browser.
    If the cached token is missing or unrefreshable, raises RuntimeError so the
    caller falls back to skip-and-log instead of hanging on a consent prompt. A
    normally-expired access token is refreshed silently.

    allow_consent=True is only for the one-time interactive setup.
    """
    creds = None
    if os.path.exists(token_file):
        creds = Credentials.from_authorized_user_file(token_file, scopes)
    if not creds or not creds.valid:
        if creds and creds.expired and creds.refresh_token:
            creds.refresh(Request())  # silent, no browser
        elif allow_consent:
            if not os.path.exists(CREDS):
                raise RuntimeError(f"missing OAuth client at {CREDS}")
            flow = InstalledAppFlow.from_client_secrets_file(CREDS, scopes)
            creds = flow.run_local_server(port=0)
        else:
            raise RuntimeError(
                "no valid cached Gmail token and consent disabled in this context"
            )
        with open(token_file, "w") as f:
            f.write(creds.to_json())
        os.chmod(token_file, 0o600)
    return build("gmail", "v1", credentials=creds)


def _self_email_hint():
    """Best-effort account hint for the consent prompt below, read from
    inbox_reader/user_mail.json (generated by setup/render_templates.py). Returns None
    (not a hard error) if the file is missing — this is guidance text only, and OAuth
    setup may legitimately run before that file exists."""
    path = os.path.join(HERE, "user_mail.json")
    if not os.path.isfile(path):
        return None
    try:
        import json
        with open(path, encoding="utf-8") as fh:
            emails = (json.load(fh).get("self_emails") or [])
        return emails[0] if emails else None
    except Exception:
        return None


if __name__ == "__main__":
    # One-time interactive consent bootstrap. Run AFTER the matching scope is
    # added on the Google Cloud OAuth consent screen:
    #   python gmail_auth.py --modify    -> gmail.modify   -> token_modify.json  (F-4 sweep)
    #   python gmail_auth.py --readonly  -> gmail.readonly -> token.json         (F-2 re-auth)
    if "--modify" in sys.argv:
        scopes, token_file, label = SCOPES_MODIFY, TOKEN_MODIFY, "gmail.modify"
    else:
        scopes, token_file, label = SCOPES_READONLY, TOKEN_READONLY, "gmail.readonly"
    print(f"Authorizing {label} -> {os.path.basename(token_file)}")
    _hint = _self_email_hint()
    if _hint:
        print(f"A browser window will open; sign in as {_hint} and accept the")
    else:
        print("A browser window will open; sign in with your Gmail account and accept the")
    print("'unverified app' warning (Advanced -> Go to ... ; expected for owner use).")
    get_service(scopes=scopes, token_file=token_file, allow_consent=True)
    print(f"OK — wrote {token_file}")
